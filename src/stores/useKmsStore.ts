import {defineStore} from "pinia";
import {shallowRef} from "vue";
import {from, useObservable} from "@vueuse/rxjs";
import {liveQuery} from "dexie";
import {
    CarmentisKmsClient,
    KmsError,
    KmsPrivateSignatureKey,
    KmsWalletAdmin,
    SeedEncoder,
    SignatureSchemeId,
    WalletCrypto,
    type KmsPlugin,
    type SignatureJwk,
} from "@cmts-dev/carmentis-sdk-core";
import {db} from "../db/db.ts";
import {KeyType, type KmsKey, type KmsServer} from "../types/types.ts";
import {WalletUtils} from "../utils/WalletUtils.ts";

/** Methods a plugin must support for Desk to create and use its wallets. */
const REQUIRED_METHODS = ["key/create", "sign/raw"];

/** Signature scheme of the admin keys generated by Desk. */
const ADMIN_KEY_SCHEME = SignatureSchemeId.SECP256K1;

export interface KmsWalletRequest {
    pluginId: string;
    params?: Record<string, unknown>;
    label?: string;
}

/** Removes the trailing slashes and checks the URL is an http(s) one. */
export function normalizeKmsUrl(url: string): string {
    const parsed = new URL(url.trim());
    if (parsed.protocol !== "https:" && parsed.protocol !== "http:") {
        throw new Error("The KMS URL must start with https:// or http://");
    }
    return parsed.toString().replace(/\/+$/, "");
}

/** The JSON Schema of the `key/create` parameters of a plugin, if any. */
export function getKeyCreationSchema(plugin: KmsPlugin): Record<string, unknown> | undefined {
    return plugin.capabilities.find(c => c.method === "key/create")?.params;
}

/** A message the user can act on, for errors raised while talking to a KMS. */
export function describeKmsError(error: unknown): string {
    if (error instanceof KmsError) {
        if (error.status === 403) return "This KMS does not allow creating wallets (public creation is disabled).";
        if (error.isNotFound()) return "The wallet was not found on the KMS.";
        if (error.isUnsupported()) return "The plugin of this wallet does not support this operation.";
        const body = error.body as { message?: unknown } | undefined;
        const detail = typeof body?.message === "string" ? body.message : undefined;
        return detail ? `The KMS answered ${error.status}: ${detail}` : `The KMS answered with status ${error.status}.`;
    }
    if (error instanceof Error && error.name === "AbortError") return "The KMS did not answer in time.";
    if (error instanceof TypeError) return "The KMS could not be reached. Check the URL and your connection.";
    return error instanceof Error ? error.message : String(error);
}

/**
 * Carmentis KMS servers configured in Desk, and the operations on KMS wallets.
 *
 * Each KMS wallet created by Desk has its own admin key (a Secp256k1 key derived from a random seed),
 * stored with the wallet API key in the wallet key entry of Stronghold.
 */
export const useKmsStore = defineStore("kms", () => {
    const servers = useObservable<KmsServer[], KmsServer[]>(
        from(liveQuery(() => db.kmsServers.orderBy("id").toArray())),
        {initialValue: []},
    );

    // the plugins of a server only change when the KMS administrators install or remove one
    const pluginsCache = shallowRef(new Map<string, Promise<KmsPlugin[]>>());

    function client(url: string) {
        return new CarmentisKmsClient({baseUrl: url});
    }

    /** Plugins of a server that can create wallets usable by Desk. */
    function fetchPlugins(url: string, refresh = false): Promise<KmsPlugin[]> {
        const cached = pluginsCache.value.get(url);
        if (cached && !refresh) return cached;
        const request = client(url).listPlugins().then(plugins => plugins.filter(plugin =>
            REQUIRED_METHODS.every(method => plugin.capabilities.some(c => c.method === method))));
        // a failed request must not stay in the cache
        request.catch(() => pluginsCache.value.delete(url));
        pluginsCache.value.set(url, request);
        return request;
    }

    /** Absolute URL of a plugin icon (the KMS may return a path relative to its base URL). */
    function pluginIconUrl(url: string, plugin: KmsPlugin): string | undefined {
        if (!plugin.icon) return undefined;
        try {
            return new URL(plugin.icon, `${url}/`).toString();
        } catch {
            return undefined;
        }
    }

    /** Adds a server after checking it answers. Returns the number of usable plugins. */
    async function addServer(name: string, url: string): Promise<number> {
        const baseUrl = normalizeKmsUrl(url);
        if (await db.kmsServers.where({url: baseUrl}).first()) {
            throw new Error("This KMS is already configured.");
        }
        const plugins = await fetchPlugins(baseUrl, true);
        await db.kmsServers.add({name: name.trim() || new URL(baseUrl).host, url: baseUrl, createdAt: new Date()});
        return plugins.length;
    }

    /** Removes a server from the settings. Its wallets keep working: they hold their own copy of the URL. */
    async function removeServer(id: number) {
        const server = await db.kmsServers.get(id);
        await db.kmsServers.delete(id);
        if (server) pluginsCache.value.delete(server.url);
    }

    async function adminFor(key: Pick<KmsKey, "serverUrl" | "adminKey">) {
        const adminKey = await WalletUtils.getPrivateKeyFromSeedAndSignatureScheme(key.adminKey.seed, key.adminKey.schemeId);
        return new KmsWalletAdmin(client(key.serverUrl), adminKey);
    }

    /**
     * Creates a wallet on the KMS, administered by a freshly generated admin key.
     * The returned key holds the wallet API key, which the KMS never returns again: store it.
     */
    async function createKmsWallet(url: string, request: KmsWalletRequest): Promise<KmsKey> {
        const adminKey = {
            schemeId: ADMIN_KEY_SCHEME,
            seed: new SeedEncoder().encode(WalletCrypto.generateWallet().getSeedAsBytes()),
        };
        const admin = await adminFor({serverUrl: url, adminKey});
        const created = await admin.createWallet({
            pluginId: request.pluginId,
            params: request.params,
            label: request.label,
        });
        return {
            keyType: KeyType.KMS,
            serverUrl: url,
            kmsWalletId: created.id,
            apiKey: created.apiKey,
            pluginId: created.pluginId,
            label: created.label,
            publicJwk: created.publicJwk,
            adminKey,
        };
    }

    /** Destroys the wallet on the KMS (private key, actor seed and API key). An already deleted wallet is not an error. */
    async function deleteKmsWallet(key: KmsKey) {
        const admin = await adminFor(key);
        try {
            await admin.deleteWallet(key.kmsWalletId);
        } catch (e) {
            if (e instanceof KmsError && e.isNotFound()) return;
            throw e;
        }
    }

    /** The wallet key as a private signature key whose signatures are made by the KMS. */
    function toPrivateKey(key: KmsKey): Promise<KmsPrivateSignatureKey> {
        const wallet = client(key.serverUrl).wallet(key.kmsWalletId, key.apiKey);
        return KmsPrivateSignatureKey.fromWallet(wallet, key.publicJwk as SignatureJwk | undefined);
    }

    return {
        servers,
        fetchPlugins,
        pluginIconUrl,
        addServer,
        removeServer,
        createKmsWallet,
        deleteKmsWallet,
        toPrivateKey,
    };
});
