<script setup lang="ts">
import {RouterLink} from 'vue-router';
import {useWalletCreationWizard, type KeyCustody} from '../../../composables/useWalletCreationWizard.ts';

const {custody, hasKmsServers} = useWalletCreationWizard();

interface CustodyOption {
    value: KeyCustody;
    icon: string;
    title: string;
    description: string;
    points: string[];
}

const OPTIONS: CustodyOption[] = [
    {
        value: 'local',
        icon: 'pi-desktop',
        title: 'On this device',
        description: 'The private key is generated or imported here, and kept in your encrypted vault.',
        points: [
            'Works offline, no third party involved',
            'You must back up the seed or passphrase yourself',
            'The wallet can be exported to a file',
        ],
    },
    {
        value: 'kms',
        icon: 'pi-server',
        title: 'In a Carmentis KMS',
        description: 'The private key is generated by a KMS server and never leaves it: the KMS signs for you.',
        points: [
            'The private key can never be copied from this device',
            'Signing needs the KMS to be reachable',
            'The private key can\'t be shown or exported',
        ],
    },
];

const isDisabled = (option: CustodyOption) => option.value === 'kms' && !hasKmsServers.value;

function select(option: CustodyOption) {
    if (!isDisabled(option)) custody.value = option.value;
}
</script>

<template>
    <div class="space-y-3">
        <p class="text-sm text-fg-muted">Where should the private key of this wallet be kept?</p>

        <div role="radiogroup" aria-label="Where the private key is kept" class="grid gap-3 sm:grid-cols-2">
            <button
                v-for="option in OPTIONS"
                :key="option.value"
                type="button"
                role="radio"
                :aria-checked="custody === option.value"
                :aria-disabled="isDisabled(option)"
                class="flex flex-col gap-3 rounded-card border bg-surface p-4 text-left shadow-card transition-colors sm:p-5"
                :class="[
                    custody === option.value ? 'border-accent ring-2 ring-accent/30' : 'border-line',
                    isDisabled(option) ? 'cursor-not-allowed opacity-60' : 'hover:border-accent/60',
                ]"
                @click="select(option)"
            >
                <span class="flex items-center gap-3">
                    <span class="flex size-10 shrink-0 items-center justify-center rounded-full bg-accent-soft text-accent">
                        <i class="pi" :class="option.icon" aria-hidden="true" />
                    </span>
                    <span class="flex-1 text-base font-semibold text-fg">{{ option.title }}</span>
                    <i
                        class="pi"
                        :class="custody === option.value ? 'pi-check-circle text-accent' : 'pi-circle text-fg-muted'"
                        aria-hidden="true"
                    />
                </span>
                <span class="text-sm text-fg-muted">{{ option.description }}</span>
                <ul class="space-y-1 text-sm text-fg">
                    <li v-for="point in option.points" :key="point" class="flex items-start gap-2">
                        <i class="pi pi-angle-right mt-1 text-xs text-fg-muted" aria-hidden="true" />
                        {{ point }}
                    </li>
                </ul>
            </button>
        </div>

        <p v-if="!hasKmsServers" class="flex items-start gap-2 text-sm text-fg-muted">
            <i class="pi pi-info-circle mt-0.5" aria-hidden="true" />
            <span>
                To keep the key in a KMS, first add a KMS server in
                <RouterLink :to="{ name: 'settings' }" class="font-medium text-accent hover:underline">Settings</RouterLink>.
            </span>
        </p>
    </div>
</template>
